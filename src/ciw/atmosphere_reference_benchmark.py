"""Fixed independent saturation references from NISTIR 5078, Table 1.

The four reference pressures are transcribed from the published IAPWS-95
table, not generated by the atmospheric compiler. A declared comparison
allowance qualifies four diagnostic points, not atmospheric observations,
condensation physics, instrument calibration or general model accuracy.
"""
from __future__ import annotations

from .atmosphere_moist_contract import example_request
from .operations.runner import seal

SOURCE_REF = "NISTIR 5078, Table 1, printed page 4 (PDF page 1)"
SOURCE_URL = "https://www.nist.gov/system/files/documents/srd/NISTIR5078-Tab1.pdf"
PROVENANCE_URL = "https://www.nist.gov/system/files/documents/srd/NISTIR5078.htm"
QUANTITY = "liquid_water_saturation_pressure_pa"
DISPLAY_ROUNDING_BOUND_PA = 0.05
RELATIVE_ALLOWANCE = 0.004

# The table prints pressure in MPa. These four pressures have been converted
# to Pa using the exact factor 1_000_000; its last printed digit is 0.1 Pa.
# Temperature is the specified independent variable of each reference point.
REFERENCE_POINTS = (
    ("nistir5078-20c", 293.15, 2339.3),
    ("nistir5078-25c", 298.15, 3169.9),
    ("nistir5078-30c", 303.15, 4247.0),
    ("nistir5078-35c", 308.15, 5629.0),
)


def _reference(pressure_pa: float) -> dict:
    return seal({
        "schema": "ciw.atmosphere-reference.v1",
        "provenance": {
            "kind": "published_reference",
            "source_ref": SOURCE_REF,
            "source_url": SOURCE_URL,
            "independent_of_candidate": True,
        },
        "context": {
            "frame": "atmosphere.local_enu.v1",
            "height_origin_m": 0.0,
            "valid_time_utc": None,
            "humidity_convention": "not_applicable",
        },
        "observations": [{
            "sample_index": 0,
            "height_m": 0.0,
            "quantities": {
                QUANTITY: {
                    "value": pressure_pa,
                    "unit": "Pa",
                    "uncertainty": {
                        "kind": "rounding_bound",
                        "absolute_bound": DISPLAY_ROUNDING_BOUND_PA,
                        "coverage_factor": None,
                        "reference": "NISTIR 5078 Table 1: 0.1 Pa display resolution; half-digit rounding bound",
                    },
                    "instrument_ref": None,
                    "calibration_ref": None,
                },
            },
        }],
    })


def _policy() -> dict:
    return seal({
        "schema": "ciw.atmosphere-comparison-policy.v1",
        "rule": "absolute_plus_relative_plus_reference_bound",
        "thresholds": {
            QUANTITY: {
                "absolute_tolerance": 0.0,
                "relative_tolerance": RELATIVE_ALLOWANCE,
            },
        },
    })


def cases() -> list[dict]:
    """Return four detached requests, published references and sealed policies.

    Each request uses the supported zero-water boundary and an isothermal
    column. Only the liquid-water saturation diagnostic at the origin is
    compared. The reference does not assert a saturated atmospheric state.
    No compiler, measurement provider or remote resource is activated here.
    """
    result = []
    for name, temperature_k, pressure_pa in REFERENCE_POINTS:
        request = example_request()
        request["reference"]["temperature_k"] = temperature_k
        request["reference"]["context"]["source_ref"] = "atmosphere.reference-benchmark." + name
        request["profile"]["lapse_rate_k_per_m"] = 0.0
        request["profile"]["water_mixing_ratio_kg_per_kg_dry_air"] = 0.0
        request["sampling"]["height_m"] = [0.0, 100.0]
        result.append({
            "name": name,
            "request": request,
            "reference": _reference(pressure_pa),
            "policy": _policy(),
        })
    return result


def example() -> dict:
    """Return the 25 degree Celsius published-reference comparison case."""
    return cases()[1]
