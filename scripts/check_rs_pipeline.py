"""Actual pinned GSC subprocess -> native COG IO -> original NET Session.

Fixtures are synthetic raster bytes generated by the pinned specialist. This is
not satellite acquisition, physical calibration, ESM admission or GSV rendering.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import json
from pathlib import Path
import subprocess
import sys
from unittest.mock import patch

from ciw.adapters.protocol import AdapterRefusal
from ciw.adapters.subprocess import PinnedSubprocessAdapter
from ciw.control_contracts import bytes_ref, load, save_new
from ciw.control_plane import builtin_registry, run_graph
from ciw.control_checks import compare, validate_comparison
from ciw.instruments import make_demo_run
from ciw.rs_operations import (RasterBinding, add_rs_routes, make_plan,
                               mean_observations, open_workspace, validate_result)
from ciw.session import Session
from ciw.spatial_requests import add_spatial_routes


def run(repo: Path, revision: str, output: Path) -> dict:
    output.mkdir(parents=True, exist_ok=False)
    checks = []
    sessions = {}

    def check(value, name):
        if not value:
            raise AssertionError(name)
        checks.append(name)

    # Verify the explicitly supplied repository before using its fixture writer.
    probe = PinnedSubprocessAdapter(repo, revision, "worker", source_root="tools/ciw-rs")
    identity = probe.runtime_identity()
    for name, extra in (("baseline", []), ("changed", ["--altered"]), ("corrupt", [])):
        subprocess.run([sys.executable, "-B", str(repo / "tools/ciw-rs/fixture.py"),
                        "--output-dir", str(output / name), *extra], check=True,
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=30)
    check(probe.runtime_identity() == identity, "fixture_setup_preserves_pinned_source")
    host_recording = make_demo_run()
    save_new(output / "host-recording.json", host_recording)

    def attach(name):
        manifest = output / name / "scene.json"
        pin = bytes_ref(manifest.read_bytes())
        binding = RasterBinding(repo, revision, manifest, pin)
        registry = builtin_registry()
        add_spatial_routes(registry)
        add_rs_routes(registry, binding=binding)
        session = Session(host_recording, output / (name + "-run"), operations=registry.operations)
        sessions[name] = session
        request = load(output / name / "ndvi-request.json")["parameters"]
        return session, registry, binding, {"bundle_ref": pin, "request": request}

    def execute(lab, operation="rs.index.ndvi.v1", parameters=None, label="run"):
        session, registry, _, default = lab
        graph = make_plan(operation, default if parameters is None else parameters)
        before = set(session.results)
        outcome = run_graph(session, graph, registry)
        save_new(output / f"{label}-plan.json", graph)
        save_new(output / f"{label}-graph.json", outcome)
        records = [r for k, r in session.results.items() if k not in before]
        return outcome, records[0] if records else None

    try:
        a = attach("baseline")
        before = {p.name: bytes_ref(p.read_bytes()) for p in (output / "baseline").iterdir()}
        info, metadata = execute(a, "rs.scene.inspect.v1", label="metadata")
        check(info["status"] == "completed" and metadata["data"]["specialist_result"]["index"] is None,
              "native_scene_inspection_has_no_ndvi_result")
        done, baseline = execute(a, label="baseline")
        repeated, replica = execute(a, label="replica")
        check(done["status"] == repeated["status"] == "completed", "native_ndvi_and_reproduction_completed")
        for result in (metadata, baseline, replica):
            validate_result(result)
        raw = baseline["data"]["specialist_result"]
        ix = raw["index"]
        check(ix["valid_count"] == 13 and ix["total_count"] == 16
              and ix["excluded_counts"] == {"nodata":1, "quality_mask":1, "nonfinite_input":0,
                                             "zero_denominator":1, "nonfinite_result":0},
              "independent_coverage_counts_no_imputation")
        check(abs(ix["mean"] - 6/13) <= 1e-12 and abs(ix["values"][0] - 0.5) <= 1e-12
              and ix["values"][1] == 0 and ix["values"][2:4] == [None, None]
              and ix["values"][4] is None, "independent_pixel_and_mean_reference")
        check(raw["source"]["license_posture"] == "synthetic" and raw["source"]["knownAt"] == "2026-09-28T12:00:00Z"
              and raw["scene"]["valid_time"]["start"] == "2026-09-26T12:00:00Z",
              "synthetic_provenance_and_separate_acquisition_knowledge_time")
        check(raw["scene"]["scene_cloud_cover_percent"] is None
              and raw["scene"]["cloud_cover_scope"] == "scene_metadata_not_window_measurement",
              "unknown_scene_cloud_cover_is_not_window_cloud_measurement")
        check(raw["grid"]["crs"] == "EPSG:32617" and raw["grid"]["axis_order"] == ["easting", "northing"]
              and raw["selection"]["bounds_xy"] == [500000, 4799960, 500040, 4800000],
              "actual_native_grid_and_pixel_window_metadata")
        check(all(x["cog_layout_marker"] and x["cog_conformance"] == "not_certified" for x in raw["assets"].values()),
              "real_cog_files_not_conformance_certificate")
        check(baseline["execution_id"] != replica["execution_id"]
              and raw["provider_execution_id"] != replica["data"]["specialist_result"]["provider_execution_id"]
              and baseline["execution_id"] != raw["provider_execution_id"],
              "new_host_and_specialist_occurrences_for_explicit_reproduction")
        left, right = mean_observations(replica), mean_observations(baseline)
        equal = compare(left["observations"], right["observations"], atol=1e-12, rtol=0)
        check(equal["outcome"]["status"] == "PASS", "existing_typed_comparator_reproduction_pass")
        b = attach("changed")
        state, changed = execute(b, label="changed")
        check(state["status"] == "completed" and abs(changed["data"]["specialist_result"]["index"]["mean"] - 11/26) <= 1e-12,
              "independent_changed_band_reference")
        different = compare(mean_observations(changed)["observations"], right["observations"], atol=1e-12, rtol=0)
        check(different["outcome"]["status"] == "FAIL"
              and abs(different["outcome"]["metrics"]["max_abs_error"] - 1/26) <= 1e-12,
              "existing_comparator_detects_changed_band_without_ranking")
        unmasked = deepcopy(a[3]); unmasked["request"]["quality"] = "none"
        state, no_mask = execute(a, parameters=unmasked, label="unmasked")
        coverage = compare(mean_observations(no_mask)["observations"], right["observations"], atol=1e-12, rtol=0)
        check(state["status"] == "completed" and no_mask["data"]["specialist_result"]["index"]["valid_count"] == 14
              and coverage["outcome"]["status"] == "INDETERMINATE", "different_support_not_silently_comparable")
        outside = deepcopy(a[3]); outside["request"]["window"] = [4, 0, 1, 1]
        rejected, none = execute(a, parameters=outside, label="outside")
        check(rejected["status"] != "completed" and none is None
              and list(a[0].executions.values())[-1]["status"] == "refused", "out_of_scene_window_retains_refusal_no_result")
        check(before == {p.name: bytes_ref(p.read_bytes()) for p in (output / "baseline").iterdir()},
              "scene_item_and_asset_bytes_unchanged")
        c = attach("corrupt")
        manifest = load(output / "corrupt/scene.json")
        asset = output / "corrupt" / manifest["assets"][manifest["bands"]["red"]]["path"]
        asset.write_bytes(asset.read_bytes() + b"deliberate-invalid-hash")
        rejected, none = execute(c, label="corrupt")
        check(rejected["status"] != "completed" and none is None and len(c[0].results) == 0,
              "changed_asset_hash_refuses_in_original_session")
        check(all(s.run == host_recording for s in sessions.values()), "host_recording_not_rewritten_as_raster_state")
        check(all(not a[1].catalog()["operations"][op]["bound"] for op in
                  ("rs.scene.admit.v1", "spatial.map.v1", "spatial.inspect.v1")),
              "admission_map_and_public_projection_remain_unbound")
        check(raw["state_admission"] == raw["state_release"] == "not_performed"
              and baseline["verification_id"] is None, "numerical_execution_is_not_admission_release_or_verification")
        for name, comp in (("replica", equal), ("changed", different), ("support", coverage)):
            validate_comparison(comp); save_new(output / f"{name}-comparison.json", comp)
        for name, result in (("baseline", baseline), ("replica", replica), ("changed", changed)):
            save_new(output / f"{name}-observations.json", mean_observations(result))
    finally:
        for name, session in sessions.items():
            session.save_workspace(output / f"{name}-workspace.json")
    with patch("subprocess.Popen", side_effect=AssertionError("retained inspection must not execute")):
        for name, session in sessions.items():
            reader = open_workspace(output / f"{name}-workspace.json", output_dir=output / f"{name}-reader")
            check(reader.results == session.results and reader.executions == session.executions,
                  f"{name}_workspace_reopens_without_provider")
    report = {"status":"passed", "checks":checks, "count":len(checks),
              "provider_revision":revision, "source_profile":"explicitly_generated_synthetic_COGs",
              "runtime":raw["runtime"], "baseline_mean":ix["mean"], "baseline_valid_pixels":ix["valid_count"],
              "changed_mean":changed["data"]["specialist_result"]["index"]["mean"],
              "comparison_statuses":[equal["outcome"]["status"], different["outcome"]["status"], coverage["outcome"]["status"]],
              "executions":sum(len(s.executions) for s in sessions.values()),
              "results":sum(len(s.results) for s in sessions.values()),
              "imagery_acquisition":"not_performed", "admission":"not_performed", "release":"not_performed"}
    save_new(output / "report.json", report)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gsc-repo", type=Path, required=True)
    parser.add_argument("--gsc-revision", required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    result = run(args.gsc_repo.resolve(), args.gsc_revision, args.output_dir.resolve())
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
