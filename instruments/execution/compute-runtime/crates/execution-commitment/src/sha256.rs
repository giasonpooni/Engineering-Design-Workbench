//! SHA-256 (FIPS 180-4), implemented here rather than depended upon.
//!
//! # Why this is not a dependency
//!
//! This repository's Python side declares `dependencies = []`, and
//! `evidence/identity.py` already commits to SHA-256 hex as THE identity
//! primitive:
//!
//! ```python
//! def content_hash(payload):
//!     return hashlib.sha256(canonical_json_bytes(payload)).hexdigest()
//! ```
//!
//! Reusing that primitive rather than inventing a second one is the
//! instruction. What is NOT reused is the canonical JSON step: execution
//! identities commit to raw program and I/O bytes, and canonicalising an
//! ELF binary as JSON would be a category error. The shared primitive is
//! the hash and its hex form; the encoding above it is domain-specific
//! (see `execution-serialization`).
//!
//! Phase 126's version-binding finding is the second reason. If
//! `ProgramIdentity` were computed by a third-party crate, the identity
//! of a program would depend on which version of that crate computed it.
//! SHA-256 is a fixed, published function with published test vectors;
//! it cannot drift, and `tests/` checks it against both the FIPS 180-4
//! vectors and Python's own `hashlib`.

